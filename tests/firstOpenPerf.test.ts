const FIRST_NAMES = ['Ava', 'Liam', 'Noah', 'Mia', 'Ethan', 'Zoe', 'Kai', 'Priya', 'Diego', 'Freya', 'Omar', 'Nina', 'Leo', 'Grace', 'Marcus'];
const LAST_NAMES = ['Stone', 'Cross', 'Vance', 'Blackwood', 'Rivers', 'Bennett', 'Sutton', 'Nandan', 'Salas', 'Lindqvist'];
const MODULE_POOL = ['orbit', 'ledger', 'beacon', 'lattice', 'harbor', 'pixel', 'nimbus', 'cobalt', 'ripple', 'forge', 'atlas', 'quartz', 'vector', 'meadow', 'signal'];
const MESSAGE_TEMPLATES = [
	'feat: add %s pagination support', 'fix: correct %s timeout handling', 'refactor: simplify %s pipeline internals',
	'chore: bump %s dependency versions', 'docs: expand %s usage guide', 'test: add regression coverage for %s'
];

function mulberry32(seed: number): () => number {
	let s = seed;
	return () => {
		s |= 0; s = (s + 0x6D2B79F5) | 0;
		let t = Math.imul(s ^ (s >>> 15), 1 | s);
		t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
		return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
	};
}
function pick<T>(rng: () => number, arr: ReadonlyArray<T>): T {
	return arr[Math.floor(rng() * arr.length)];
}
function authorPool(count: number): { name: string, email: string }[] {
	const authors = [];
	for (let i = 0; i < count; i++) {
		const first = FIRST_NAMES[i % FIRST_NAMES.length];
		const last = LAST_NAMES[Math.floor(i / FIRST_NAMES.length) % LAST_NAMES.length];
		authors.push({ name: first + ' ' + last, email: (first + '.' + last).toLowerCase() + '@example.com' });
	}
	return authors;
}
const AUTHORS = authorPool(45);

/** Run a Git command synchronously (used to BUILD the test repository). */
function git(cwd: string, args: string[]) {
	const result = cp.spawnSync('git', args, { cwd: cwd, encoding: 'utf8' });
	if (result.status !== 0) {
		throw new Error('git ' + args.join(' ') + ' failed in ' + cwd + ':\n' + result.stderr);
	}
	return (result.stdout || '').trim();
}

/** Builder of a `git fast-import` stream (trimmed to what a plain, non-Gerrit history needs). */
class FastImport {
	private chunks: string[] = [];
	private mark = 0;

	constructor(private readonly repo: string) { }

	private data(content: string) {
		this.chunks.push('data ' + Buffer.byteLength(content, 'utf8'));
		this.chunks.push(content);
	}

	public commit(ref: string, epoch: number, fromMark?: number) {
		this.mark++;
		const rng = mulberry32(this.mark);
		const author = pick(rng, AUTHORS);
		const message = pick(rng, MESSAGE_TEMPLATES).replace('%s', pick(rng, MODULE_POOL)) + '\n';
		this.chunks.push('commit ' + ref, 'mark :' + this.mark);
		const identity = author.name + ' <' + author.email + '> ' + epoch + ' +0000';
		this.chunks.push('author ' + identity, 'committer ' + identity);
		this.data(message);
		if (fromMark !== undefined) this.chunks.push('from :' + fromMark);
		return this.mark;
	}

	/** Create a merge commit on `ref`, with `fromMark` as the first parent and `mergeMark` as the second. */
	public merge(ref: string, epoch: number, fromMark: number, mergeMark: number) {
		this.mark++;
		const rng = mulberry32(this.mark);
		const author = pick(rng, AUTHORS);
		this.chunks.push('commit ' + ref, 'mark :' + this.mark);
		const identity = author.name + ' <' + author.email + '> ' + epoch + ' +0000';
		this.chunks.push('author ' + identity, 'committer ' + identity);
		this.data('merge: bring in a feature branch\n');
		this.chunks.push('from :' + fromMark, 'merge :' + mergeMark);
		return this.mark;
	}

	public tag(name: string, mark: number, epoch: number) {
		this.chunks.push('tag ' + name, 'from :' + mark, 'tagger Dev <dev@example.com> ' + epoch + ' +0000');
		this.data('release ' + name + '\n');
	}

	public run() {
		const result = cp.spawnSync('git', ['fast-import', '--quiet'], { cwd: this.repo, input: this.chunks.join('\n') + '\ndone\n', encoding: 'utf8' });
		if (result.status !== 0) {
			throw new Error('git fast-import failed in ' + this.repo + ':\n' + result.stderr);
		}
	}
}

/**
 * Build a large fictional repository ON DISK (a trunk with many feature branches, most merged
 * back, some left open, and many tags scattered across the trunk) - the same DAG shape as
 * webviewUiPerf.test.ts's in-memory generator, but this time emitting real Git objects via
 * `git fast-import`, so the DataSource operations below spawn real `git` processes.
 */
function buildRepository(repo: string) {
	const rng = mulberry32(0xC0FFEE);
	const epoch = (i: number) => BASE_EPOCH + i * hour;
	const imp = new FastImport(repo);

	let trunkTip = imp.commit('refs/heads/main', epoch(1));
	const trunkMarks = [trunkTip];
	for (let i = 1; i < TRUNK_COMMITS; i++) {
		trunkTip = imp.commit('refs/heads/main', epoch(i + 1), trunkTip);
		trunkMarks.push(trunkTip);
	}

	const perBranch = Math.max(1, Math.round((TRUNK_COMMITS * 0.6) / BRANCHES));
	const branchSpan = perBranch * 2 + 5; // epoch slots reserved per branch, wide enough that its commits never overlap the next branch's
	for (let b = 0; b < BRANCHES; b++) {
		const branchName = 'feature/' + pick(rng, MODULE_POOL) + '-' + (b + 1);
		let tip = trunkMarks[Math.floor(rng() * trunkMarks.length)];
		const branchCommitCount = 1 + Math.floor(rng() * perBranch * 2);
		const branchEpoch = TRUNK_COMMITS + 100 + b * branchSpan;
		for (let c = 0; c < branchCommitCount; c++) tip = imp.commit('refs/heads/' + branchName, epoch(branchEpoch + c), tip);

		if (rng() < 0.65) {
			// merged back into the trunk (a real 2-parent merge commit)
			trunkTip = imp.merge('refs/heads/main', epoch(branchEpoch + branchCommitCount + 1), trunkTip, tip);
			trunkMarks.push(trunkTip);
		}
		// else: left as an open branch ref (already created above by the `commit` calls)
	}

	for (let t = 0; t < TAGS; t++) {
		const mark = trunkMarks[Math.floor(rng() * trunkMarks.length)];
		imp.tag('v' + (1 + Math.floor(t / 20)) + '.' + (t % 20) + '.0', mark, epoch(TRUNK_COMMITS + 200 + t));
	}

	imp.run();
	git(repo, ['checkout', '-q', 'main']);
}

/* Measure the wall-clock time (ms) of an async operation. */
async function timed<T>(fn: () => Promise<T>): Promise<{ value: T, ms: number }> {
	const start = Date.now();
	const value = await fn();
	return { value: value, ms: Date.now() - start };
}

/* Count how many Git processes an async operation spawns. */
async function countSpawns<T>(fn: () => Promise<T>): Promise<{ value: T, ms: number, spawns: number }> {
	const realSpawn = cp.spawn.bind(cp);
	let spawns = 0;
	const spy = jest.spyOn(cp, 'spawn').mockImplementation(((command: string, args: readonly string[], options: any) => {
		spawns++;
		return realSpawn(command, args as any[], options);
	}) as any);
	try {
		const { value, ms } = await timed(fn);
		return { value: value, ms: ms, spawns: spawns };
	} finally {
		spy.mockRestore();
	}
}

function rmRecursive(target: string) {
	if (!fs.existsSync(target)) return;
	for (const entry of fs.readdirSync(target)) {
		const entryPath = path.join(target, entry);
		try {
			if (fs.statSync(entryPath).isDirectory()) rmRecursive(entryPath);
			else fs.unlinkSync(entryPath);
		} catch (e) {
			// A Git subprocess may delete an entry (e.g. .git/index.lock) concurrently with
			// this cleanup: an entry that is already gone needs no removal.
			if (e.code !== 'ENOENT') throw e;
		}
	}
	fs.rmdirSync(target);
}

