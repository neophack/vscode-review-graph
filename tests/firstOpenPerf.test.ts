/**
 * "First open" end-to-end performance benchmark: measures the FULL pipeline a user actually waits
 * on when opening Git Graph on a large repository for the first time - real `git` processes spawned
 * against a large REAL repository on disk (not fabricated in-memory data, unlike webviewUiPerf.test.ts),
 * through to the compiled webview bundle (media/out.min.js) rendering the result in jsdom.
 *
 * It also runs the SAME backend request twice (COLD: a fresh DataSource, as on the very first open
 * after VS Code starts; WARM: a second fresh DataSource against the same on-disk repo moments later,
 * as when re-opening the view again in the same session) and compares them. This directly tests
 * whether "slow on first open, fast afterwards" is something the extension's code controls, or an
 * external cold-cache effect (the OS hasn't yet paged a large .git directory into memory) that no
 * amount of code change fixes - the first read of a multi-GB repository from disk is inherently
 * slower than reading the same bytes again a moment later once the OS has cached them.
 *
 * All repository data (author names/emails, branch/tag names, commit messages) is entirely
 * FICTIONAL and generated by a seeded PRNG - nothing is derived from any real repository. Scale is
 * shaped after a large, actively-developed project (thousands of commits, 100+ branches).
 */
